def validate_annotation(obj):
    try:
        validate(instance=obj, schema=ANNOTATION_SCHEMA)
        return True, None
    except ValidationError as e:
        return False, str(e)

def normalize_annotation_enums(obj):
    """
    Normalize category and subcategory strings to match the schema enums.
    - category: fix capitalization for 'No Polarizing language'
    - subcategory: lowercase and map simple variants like 'Slogans' -> 'slogans',
      'No Polarizing Language' -> 'no polarizing language'
    """
    if "annotations" not in obj:
        return obj

    # Valid categories
    valid_categories = {
        "persuasive propaganda": "Persuasive Propaganda",
        "inflammatory language": "Inflammatory Language",
        "no polarizing language": "No Polarizing language",  # note lowercase 'l' in 'language'
    }

    # Valid subcategories (including the "no polarizing language" catch-all)
    valid_subcategories = {
        "exaggeration": "exaggeration",
        "slogans": "slogans",
        "slogan": "slogans",
        "bandwagon": "bandwagon",
        "causal oversimplification": "causal oversimplification",
        "doubt": "doubt",
        "name-calling": "name-calling",
        "name calling": "name-calling",
        "demonization": "demonization",
        "scapegoating": "scapegoating",
        "no polarizing language": "no polarizing language",
        "no polarizing": "no polarizing language",
    }

    for ann in obj.get("annotations", []):
        # Normalize category
        cat = ann.get("category")
        if isinstance(cat, str):
            key = cat.strip().lower()
            if key in valid_categories:
                ann["category"] = valid_categories[key]

        # Normalize subcategory
        sub = ann.get("subcategory")
        if isinstance(sub, str):
            key = sub.strip().lower()
            if key in valid_subcategories:
                ann["subcategory"] = valid_subcategories[key]

    return obj

def build_article_text(row):
    title = str(row["Headline"])
    body = str(row["News body"])
    topic = str(row["Topic"])
    source = str(row["News Source"])
    rating = str(row["Rating"])

    article_block = (
        f"TITLE: {title}\n"
        f"TOPIC: {topic}\n"
        f"SOURCE: {source}\n"
        f"RATING: {rating}\n\n"
        f"BODY:\n{body}"
    )
    return title, topic, source, rating, article_block


def build_user_prompt_for_annotation(article_block):
    return (
        "You will annotate the following news article for inflammatory language and persuasive propaganda.\n"
        "Follow the system instructions and JSON schema exactly.\n\n"
        "ARTICLE:\n"
        f"{article_block}\n\n"
        "Return ONLY a single JSON object, no backticks, no explanation."
    )

def annotate_with_openai_A(article_block, title, topic, source, rating):
    role_desc = (
        "You are Annotator A, a political communication scholar. "
        "You specialize in media framing and propaganda analysis. Strictly follow "
        "the codebook and JSON schema."
    )
    user_prompt = build_user_prompt_for_annotation(article_block)

    completion = openai_client.chat.completions.create(
        model="gpt-5.1",   # adjust to your available GPT-5 model name if needed
        temperature=0.1,
        messages=[
            {"role": "system", "content": SYSTEM_INSTRUCTIONS + "\n\n" + role_desc},
            {"role": "user", "content": user_prompt},
        ]
    )

    raw = completion.choices[0].message.content.strip()
    try:
        obj = json.loads(raw)
    except json.JSONDecodeError:
        raise ValueError(f"OpenAI Annotator A returned non-JSON:\n{raw}")

    # Ensure meta fields are present
    obj.setdefault("title", title)
    obj.setdefault("topic", topic)
    obj.setdefault("source", source)
    obj.setdefault("rating", rating)
    obj = normalize_annotation_enums(obj)
    ok, err = validate_annotation(obj)
    if not ok:
        raise ValueError(f"OpenAI Annotator A JSON failed schema validation: {err}\n\n{raw}")

    return obj, raw

def extract_json_from_text(text: str) -> str:
    """
    Extract the first top-level JSON object from a text string.
    Handles cases where the model wraps JSON in ```json ... ``` fences
    or adds extra prose before/after.
    """
    text = text.strip()
    # If it's already clean JSON, try directly first
    if text.startswith("{") and text.endswith("}"):
        return text

    # Otherwise, find the first '{' and last '}' and slice
    start = text.find("{")
    end = text.rfind("}")
    if start == -1 or end == -1 or end <= start:
        raise ValueError(f"No JSON object found in text:\n{text}")

    return text[start:end + 1]

